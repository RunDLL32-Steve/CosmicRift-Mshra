#!/usr/bin/env python3
"""Offline tests for scripts/review-queue.py (BBQ / cooked rules). Run: python -m unittest scripts/test_review_queue.py -v"""
import importlib.util, unittest
from pathlib import Path

spec = importlib.util.spec_from_file_location("review_queue", Path(__file__).with_name("review-queue.py"))
rq = importlib.util.module_from_spec(spec)
spec.loader.exec_module(rq)

FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def pr(labels=("review-pending",), draft=False, n=7):
    return {"number": n, "head_sha": "h" * 40, "labels": list(labels), "draft": draft}


def commits(*subjects):
    return [{"sha": f"{i:040x}", "message": s} for i, s in enumerate(subjects, 1)]


def review(commit_index, when="2026-10-16T10:00:00Z", body="Review round 1 (senior review): APPROVED"):
    return {"id": 1, "commit_id": f"{commit_index:040x}", "submitted_at": when, "body": body}


def comment(body, when, cid=100):
    return {"id": cid, "created_at": when, "body": body}


class LastWord(unittest.TestCase):
    def test_cooked_variants(self):
        for body in ["done, cooked", "Rework after round 1 ... cooked.", "COOKED!", "all fixed\n\ncooked\n", "**cooked**",
                     "fixed in abc123 - cooked  ", "Fixed in `abc`: split the test. cooked" + FOOTER, "(cooked)"]:
            self.assertTrue(rq.is_cooked(body), body)

    def test_not_cooked(self):
        for body in ["", None, "uncooked", "cooked it", "cooked is the keyword", "I have cooked this and more", "precooked",
                     "ready for review" + FOOTER, "cooked\nbut I forgot the end", "not-cooked yet"]:
            self.assertFalse(rq.is_cooked(body), body)

    def test_footer_is_ignored_only_at_the_end(self):
        self.assertFalse(rq.is_cooked("cooked" + FOOTER + "\nmore text after"))


class Markers(unittest.TestCase):
    def test_bbq(self):
        for m in ["BBQ RT-F033 ready", "bbq", "BBQ: done\n\nbody", "  Bbq - x"]:
            self.assertTrue(rq.is_bbq(m), m)
        for m in ["bbqueue", "Add BBQ later", "", None, "REVIEW round 1: APPROVED"]:
            self.assertFalse(rq.is_bbq(m), m)

    def test_review_commit(self):
        self.assertTrue(rq.is_review_commit("REVIEW round 3: APPROVED (PR #5)"))
        self.assertFalse(rq.is_review_commit("Reviewed tests and added more"))
        self.assertFalse(rq.is_review_commit("BBQ RT-F033"))


class Classify(unittest.TestCase):
    def go(self, p, cs, rs=(), ms=()):
        return rq.classify(p, cs, list(rs), list(ms))

    def test_bbq_ready_never_reviewed(self):
        r = self.go(pr(), commits("CLAIM RT-F033", "Add parser", "BBQ RT-F033 ready"))
        self.assertEqual(r["action"], "REVIEW")
        self.assertTrue(r["bbq_ready"])

    def test_in_progress_without_bbq_is_skipped(self):
        r = self.go(pr(), commits("CLAIM RT-F033", "BBQ RT-F033 ready", "more work after bbq"), [review(2)])
        self.assertEqual(r["action"], "SKIP")
        self.assertFalse(r["bbq_ready"])

    def test_reviewed_at_bbq_is_skipped_even_with_reviewer_log_commit_on_top(self):
        cs = commits("CLAIM", "work", "BBQ RT-F033", "REVIEW round 1: APPROVED (PR #7)")
        r = self.go(pr(("review-approved",)), cs, [review(3)])
        self.assertEqual(r["action"], "SKIP")
        self.assertEqual(r["newest_dev_commit"], f"{3:040x}"[:7])

    def test_review_of_log_commit_also_covers_bbq(self):
        cs = commits("CLAIM", "BBQ RT-F033", "REVIEW round 1: APPROVED")
        self.assertEqual(self.go(pr(), cs, [review(3)])["action"], "SKIP")

    def test_new_bbq_after_review_triggers_again(self):
        cs = commits("CLAIM", "BBQ first", "REVIEW round 1: CHANGES REQUESTED", "fix findings", "BBQ rework")
        r = self.go(pr(("review-pending",)), cs, [review(2)])
        self.assertEqual(r["action"], "REVIEW")

    def test_cooked_comment_after_review_summons_even_without_bbq(self):
        cs = commits("CLAIM", "BBQ first", "more work")
        ms = [comment("Rework after round 1 - cooked", "2026-10-16T11:00:00Z")]
        r = self.go(pr(("review-changes-requested",)), cs, [review(2)], ms)
        self.assertEqual(r["action"], "REVIEW")
        self.assertEqual(r["cooked_comments"], [100])

    def test_cooked_comment_before_the_review_is_not_a_summons(self):
        cs = commits("CLAIM", "BBQ first")
        ms = [comment("done cooked", "2026-10-16T09:00:00Z")]
        r = self.go(pr(("review-approved",)), cs, [review(2, "2026-10-16T10:00:00Z")], ms)
        self.assertEqual(r["action"], "SKIP")

    def test_comment_not_ending_in_cooked_is_ignored(self):
        cs = commits("CLAIM", "BBQ first", "wip")
        ms = [comment("still working on it, cooked soon", "2026-10-16T11:00:00Z")]
        self.assertEqual(self.go(pr(), cs, [review(2)], ms)["action"], "SKIP")

    def test_reviewer_style_comment_with_footer_is_not_cooked(self):
        cs = commits("CLAIM", "wip")
        ms = [comment("Merge gate: not merged, conflict." + FOOTER, "2026-10-16T11:00:00Z")]
        self.assertEqual(self.go(pr(("review-changes-requested",)), cs, (), ms)["action"], "SKIP")

    def test_cooked_with_footer_still_summons(self):
        cs = commits("CLAIM", "wip")
        ms = [comment("Conflict merged, tests pass, cooked" + FOOTER, "2026-10-16T11:00:00Z")]
        self.assertEqual(self.go(pr(("review-pending",)), cs, (), ms)["action"], "REVIEW")

    def test_legacy_pr_without_bbq_pending_and_never_reviewed(self):
        r = self.go(pr(), commits("CLAIM RT-F033", "work"))
        self.assertEqual(r["action"], "REVIEW")
        self.assertIn("legacy", r["reasons"][0])

    def test_legacy_pr_already_reviewed_waits(self):
        r = self.go(pr(), commits("CLAIM", "work", "REVIEW round 1"), [review(3)])
        self.assertEqual(r["action"], "SKIP")

    def test_legacy_rework_after_review_is_queued_again(self):
        cs = commits("CLAIM", "work", "REVIEW round 1: CHANGES REQUESTED", "fix findings")
        r = self.go(pr(("review-pending",)), cs, [review(3)])
        self.assertEqual(r["action"], "REVIEW")

    def test_legacy_rework_not_queued_while_label_is_changes_requested(self):
        cs = commits("CLAIM", "work", "REVIEW round 1: CHANGES REQUESTED", "half-done fix")
        r = self.go(pr(("review-changes-requested",)), cs, [review(3)])
        self.assertEqual(r["action"], "SKIP")

    def test_needs_human_and_draft_never_queue(self):
        cs = commits("CLAIM", "BBQ ready")
        self.assertEqual(self.go(pr(("needs-human",)), cs, (), [comment("x cooked", "2026-10-16T11:00:00Z")])["action"], "SKIP")
        self.assertEqual(self.go(pr(draft=True), cs)["action"], "SKIP")

    def test_review_with_empty_body_does_not_count(self):
        cs = commits("CLAIM", "BBQ ready")
        empty = review(2, body="")
        self.assertEqual(self.go(pr(), cs, [empty])["action"], "REVIEW")

    def test_review_of_unknown_sha_does_not_cover(self):
        cs = commits("CLAIM", "BBQ ready")
        stale = {"id": 9, "commit_id": "f" * 40, "submitted_at": "2026-10-16T10:00:00Z", "body": "Review round 1"}
        self.assertEqual(self.go(pr(), cs, [stale])["action"], "REVIEW")


class AuthorDeclarationTests(unittest.TestCase):
    def test_parse_and_tier(self):
        self.assertEqual(rq.parse_author("x\n**Authored-by:** Sonnet 5.5 / high\n"),("Sonnet 5.5", "high"))
        self.assertIsNone(rq.parse_author("no declaration"))
        self.assertLess(rq.tier("Sonnet 5.5"), rq.tier("Opus 5.5"))

    def test_approval_must_cover_head(self):
        rv = [{"commit_id": "a", "submitted_at": "1", "body": "APPROVED"}]
        self.assertTrue(rq.approved_at_head("a", rv))
        self.assertFalse(rq.approved_at_head("b", rv))


if __name__ == "__main__":
    unittest.main()
