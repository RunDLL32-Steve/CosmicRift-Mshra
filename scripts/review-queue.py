#!/usr/bin/env python3
"""List the open pull requests that the senior reviewer must review now, by the BBQ / cooked rules.

BBQ    The developer's last commit before opening a PR (and after every rework push) is an empty commit whose
       subject starts with "BBQ". A PR is ready for review when its newest *developer* commit is a BBQ commit.
       Commits whose subject starts with "REVIEW" are the reviewer's own log-mirror commits and are skipped.
cooked A PR comment (conversation comment, inline review comment or thread reply) whose LAST WORD is "cooked" and
       that is newer than the reviewer's latest review summons the reviewer, whatever the BBQ state. A trailing
       "---" / "_Generated by ..._" footer and trailing punctuation or markdown emphasis are ignored. The reviewer
       never ends a comment with that word, so its own comments can never summon it.

Transition: a PR that has no BBQ commit anywhere in its history but is labelled review-pending is treated as ready
(legacy) while it has developer commits that no review covers, so work opened before this rule, and reworks pushed by
a routine that does not write BBQ commits yet, are not stranded.

Usage (repository root; needs an authenticated `gh`):
    python scripts/review-queue.py                 # human-readable table
    python scripts/review-queue.py --json          # machine-readable
    python scripts/review-queue.py --repo OWNER/REPO --pr 7
    python scripts/review-queue.py --audit [--since 84] [--json]   # PRs lacking an approving review at head / Authored-by
Exit status is 0 when it ran, whatever the queue holds. Standard library only; read-only (GET requests).
"""
import argparse, json, re, subprocess, sys

DEFAULT_REPO = "RunDLL32-Steve/CosmicRift-Mshra"
PUNCT = " \t\r\n.,;:!?)]}\"'`*_~>-"
FOOTER = re.compile(r"\n\s*-{3,}\s*\n\s*_?Generated by [^\n]*\s*$", re.I)
LABELS = ("review-pending", "review-changes-requested", "review-approved", "needs-human")


def last_word(body):
    """Last word of a comment body, lower-cased, ignoring the generated footer, punctuation and emphasis."""
    text = FOOTER.sub("", body or "").strip().rstrip(PUNCT)
    words = re.split(r"\s+", text)
    return words[-1].lower().lstrip("*_`~\"'([{<") if words and words[0] else ""


def is_cooked(body):
    return last_word(body) == "cooked"


def _subject(message):
    return (message or "").lstrip().split("\n", 1)[0].strip()


def is_bbq(message):
    """Subject begins with the word BBQ (case-insensitive): "BBQ RT-F033 ready for review", "bbq: done"."""
    return re.match(r"bbq\b", _subject(message), re.I) is not None


def is_review_commit(message):
    """The reviewer's own log-mirror commit: subject begins with the word REVIEW ("REVIEW round 3: APPROVED (PR #5)")."""
    return re.match(r"review\b", _subject(message), re.I) is not None


def classify(pr, commits, reviews, comments):
    """Pure decision for one PR.

    pr        {"number", "head_sha", "labels": [names], "draft": bool}
    commits   chronological [{"sha", "message"}]
    reviews   [{"id", "commit_id", "submitted_at", "body"}] (empty-bodied reviews are ignored)
    comments  [{"id", "created_at", "body"}] conversation + inline + replies together
    Returns {"action": "REVIEW" | "SKIP", "reasons": [...], ...}
    """
    labels = [l for l in pr.get("labels", []) if l in LABELS]
    out = {"number": pr["number"], "head": pr["head_sha"][:7], "labels": labels, "action": "SKIP", "reasons": []}
    if "needs-human" in labels:
        out["reasons"].append("needs-human: left for the owner")
        return out
    if pr.get("draft"):
        out["reasons"].append("draft")
        return out

    shas = [c["sha"] for c in commits]
    dev = [i for i, c in enumerate(commits) if not is_review_commit(c["message"])]
    newest_dev = dev[-1] if dev else None
    out["newest_dev_commit"] = shas[newest_dev][:7] if newest_dev is not None else None
    bbq_anywhere = any(is_bbq(c["message"]) for c in commits)
    bbq_ready = newest_dev is not None and is_bbq(commits[newest_dev]["message"])
    out["bbq_ready"] = bbq_ready

    given = [r for r in reviews if (r.get("body") or "").strip()]
    reviewed_idx = [shas.index(r["commit_id"]) for r in given if r["commit_id"] in shas]
    last_reviewed = max(reviewed_idx) if reviewed_idx else None
    covers_bbq = bbq_ready and last_reviewed is not None and last_reviewed >= newest_dev
    latest_review_time = max((r["submitted_at"] for r in given), default="")

    summons = [c["id"] for c in comments if c["created_at"] > latest_review_time and is_cooked(c["body"])]
    out["cooked_comments"] = summons

    if summons:
        out["action"] = "REVIEW"
        out["reasons"].append(f"cooked comment(s) {summons} newer than the last review")
    if bbq_ready and not covers_bbq:
        out["action"] = "REVIEW"
        out["reasons"].append("newest developer commit is BBQ and no review covers it")
    elif not bbq_anywhere and "review-pending" in labels and (last_reviewed is None or last_reviewed < newest_dev):
        out["action"] = "REVIEW"
        out["reasons"].append("legacy PR (no BBQ commit yet), labelled review-pending, with developer commits no review covers")
    elif not bbq_anywhere and "review-pending" in labels and out["action"] == "SKIP":
        out["reasons"].append("legacy PR already reviewed at its newest developer commit; waits for BBQ or cooked")
    if out["action"] == "SKIP" and not out["reasons"]:
        if covers_bbq:
            out["reasons"].append("reviewed at the BBQ commit; nothing new")
        else:
            out["reasons"].append("in progress: newest developer commit is not BBQ and no cooked comment")
    return out


AUTHOR_LINE = re.compile(r"^[ \t]*[*_]*Authored[- ]by[*_]*[ \t]*:[ \t]*[*_]*[ \t]*([^\r\n]*?)[ \t*_]*\r?$", re.I | re.M)
CANONICAL_VERDICT = re.compile(r"^\W*Verdict\W*APPROVED\W+for\W+(?:head\W+)?([0-9a-f]{7,40})\b", re.I | re.M)
VERDICT = re.compile(r"\b(?:(?i:(not|never|once|be))\s+)?(APPROVED|CHANGES[_ ]REQUESTED|REQUEST[_ ]CHANGES)\b(?!-)")


def parse_author(body):
    """`Authored-by: <model> / <effort>` line of a PR body -> (model, effort), or None when absent or empty.

    The format is strict: model and effort are separated by `/`, `,` or `;` ("Opus 5.5 (high)" keeps its effort in the model).
    """
    m = AUTHOR_LINE.search(body or "")
    if not m:
        return None
    parts = [x.strip(" \t*_") for x in re.split(r"[/,;]", m.group(1))]
    parts = [x for x in parts if x]
    return (parts[0], parts[1] if len(parts) > 1 else "") if parts else None


def review_verdict(body):
    """'approved', 'not-approved' or None (no verdict word) for a review body.

    A line `Verdict: APPROVED for <sha>` is canonical. Otherwise the FIRST verdict token decides, and a negation or
    future-tense word before APPROVED ("not", "never", "once", "be") or a suffix such as -WITH-NOTES makes it not an approval.
    """
    body = body or ""
    if CANONICAL_VERDICT.search(body):
        return "approved"
    m = VERDICT.search(body)
    if not m:
        return None
    return "approved" if m.group(2) == "APPROVED" and not m.group(1) else "not-approved"


def approved_at_head(head_sha, reviews, commits=None):
    """True when the newest review that gives a verdict approves the head.

    The approval covers the head when it names it exactly, or, if `commits` (chronological [{"sha","message"}]) is
    given, when every later commit is a reviewer log-mirror (REVIEW) or empty BBQ marker, which the merge gate allows.
    """
    verdicts = [r for r in sorted(reviews, key=lambda r: r["submitted_at"] or "") if review_verdict(r.get("body"))]
    if not verdicts or review_verdict(verdicts[-1]["body"]) != "approved":
        return False
    at = verdicts[-1]["commit_id"]
    if at == head_sha:
        return True
    if commits is None:
        return False
    shas = [c["sha"] for c in commits]
    if at not in shas:
        return False
    return all(is_review_commit(c["message"]) or is_bbq(c["message"]) for c in commits[shas.index(at) + 1:])


def audit(repo, since=0):
    """Every open or merged PR: author declaration (checked from PR #since on) and whether an approval covers its head."""
    rows = []
    for p in gh("pulls?state=all&per_page=100", repo):
        if p["state"] == "closed" and not p.get("merged_at"):
            continue
        n = p["number"]
        reviews = [{"commit_id": r["commit_id"], "submitted_at": r["submitted_at"], "body": r["body"]}
                   for r in gh(f"pulls/{n}/reviews?per_page=100", repo)]
        commits = [{"sha": c["sha"], "message": c["commit"]["message"]} for c in gh(f"pulls/{n}/commits?per_page=100", repo)]
        rows.append({"number": n, "state": "merged" if p.get("merged_at") else "open",
                     "author": parse_author(p.get("body")), "declaration_required": n >= since,
                     "approved_at_head": approved_at_head(p["head"]["sha"], reviews, commits)})
    return sorted(rows, key=lambda r: r["number"])


def gh(path, repo):
    raw = subprocess.run(["gh", "api", "--paginate", "--slurp", f"repos/{repo}/{path}"], check=True,
                         capture_output=True, text=True).stdout
    pages = json.loads(raw)
    return [x for page in pages for x in (page if isinstance(page, list) else [page])]


def load(repo, number):
    pr = gh(f"pulls/{number}", repo)[0]
    commits = [{"sha": c["sha"], "message": c["commit"]["message"]} for c in gh(f"pulls/{number}/commits?per_page=100", repo)]
    reviews = [{"id": r["id"], "commit_id": r["commit_id"], "submitted_at": r["submitted_at"], "body": r["body"]}
               for r in gh(f"pulls/{number}/reviews?per_page=100", repo)]
    comments = [{"id": c["id"], "created_at": c["created_at"], "body": c["body"]}
                for c in gh(f"issues/{number}/comments?per_page=100", repo) + gh(f"pulls/{number}/comments?per_page=100", repo)]
    info = {"number": number, "head_sha": pr["head"]["sha"], "labels": [l["name"] for l in pr["labels"]],
            "draft": pr.get("draft", False), "branch": pr["head"]["ref"], "base": pr["base"]["ref"]}
    return info, commits, reviews, comments


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--repo", default=DEFAULT_REPO)
    ap.add_argument("--pr", type=int, action="append", help="only these PR numbers")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--audit", action="store_true", help="list merged/open PRs without an approving review at head, and PRs without Authored-by")
    ap.add_argument("--since", type=int, default=84, help="with --audit: first PR number that must carry an Authored-by line")
    args = ap.parse_args(argv)
    if args.audit:
        rows = audit(args.repo, args.since)
        merged = [r["number"] for r in rows if r["state"] == "merged" and not r["approved_at_head"]]
        opened = [r["number"] for r in rows if r["state"] == "open" and not r["approved_at_head"]]
        undeclared = [r["number"] for r in rows if r["declaration_required"] and not r["author"]]
        if args.json:
            print(json.dumps({"since": args.since, "merged_without_approval": merged, "open_without_approval": opened,
                              "missing_authored_by": undeclared}, indent=2))
        else:
            print(f"merged without approval at head: {len(merged)}  {merged}")
            print(f"open without approval at head: {len(opened)}  {opened}")
            print(f"missing Authored-by (since #{args.since}): {len(undeclared)}  {undeclared}")
        return 0
    numbers = args.pr or [p["number"] for p in gh("pulls?state=open&per_page=100", args.repo)]
    results = []
    for n in sorted(numbers):
        info, commits, reviews, comments = load(args.repo, n)
        res = classify(info, commits, reviews, comments)
        res["branch"], res["base"] = info["branch"], info["base"]
        results.append(res)
    if args.json:
        print(json.dumps(results, indent=2))
    else:
        for r in results:
            print(f"#{r['number']:<3} {r['action']:<6} head={r['head']} base={r['base'][:28]:<28} labels={','.join(r['labels']) or '-':<24} {'; '.join(r['reasons'])}")
        print(f"REVIEW queue: {[r['number'] for r in results if r['action'] == 'REVIEW']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
